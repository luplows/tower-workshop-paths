#!/usr/bin/env node
/**
 * Turns `.cache/enhancement-extraction.json` (built by
 * extract-enhancement-data.mjs) into `src/data/enhancementLevels.js` --
 * the one file OQ-39 Phase 2 actually replaces. Keyed by this project's
 * own category names throughout (not mytower.app's aliased ones -- see
 * extract-enhancement-data.mjs's `ENHANCEMENT_NAME_ALIASES`), so no
 * consuming code (cheapestNextUpgrades.js, enhancementTreeSpend.js)
 * needs to change at all -- only the data itself does.
 *
 * A separate step from extraction itself so the (slow, network-bound)
 * scrape and the (instant, deterministic) file-generation can be re-run
 * independently.
 *
 * Usage: npm run generate:enhancement-data-files
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { ENHANCEMENT_CATEGORIES } from '../src/data/enhancementCategories.js'

const CACHE_PATH = new URL('../.cache/enhancement-extraction.json', import.meta.url)
const LEVELS_PATH = new URL('../src/data/enhancementLevels.js', import.meta.url)

function loadCache() {
  if (!existsSync(CACHE_PATH)) {
    throw new Error(`No cache at ${CACHE_PATH}. Run \`npm run extract:enhancement-data\` first.`)
  }
  return JSON.parse(readFileSync(CACHE_PATH, 'utf8'))
}

function main() {
  const cache = loadCache()
  const allUpgrades = ENHANCEMENT_CATEGORIES.flatMap((category) => category.upgrades)

  const missingCategories = []
  const incompleteCategories = []
  for (const upgrade of allUpgrades) {
    const entry = cache[upgrade.name]
    if (!entry || entry.error) {
      missingCategories.push(upgrade.name)
      continue
    }
    if (entry.missing) incompleteCategories.push(`${upgrade.name} (${entry.missing.length} levels)`)
    if (entry.maxLevel !== upgrade.quantity) {
      throw new Error(
        `${upgrade.name}: mytower.app's max level (${entry.maxLevel}) doesn't match enhancementCategories.js's quantity (${upgrade.quantity}) -- resolve this before generating (either a real drift worth a new Open Question, or enhancementCategories.js needs updating).`,
      )
    }
  }
  if (missingCategories.length > 0) {
    throw new Error(`Cache is missing these categories entirely: ${missingCategories.join(', ')}`)
  }
  if (incompleteCategories.length > 0) {
    throw new Error(`Cache has incomplete data for: ${incompleteCategories.join('; ')}`)
  }

  const levelsByName = {}
  for (const upgrade of allUpgrades) {
    // Rounded for the same reason generate-workshop-data-files.mjs rounds
    // its own costs -- parseAbbreviated's float multiplication produces
    // meaningless trailing noise (e.g. 8199999.999999999), not real
    // precision the ~3-significant-figure source data actually carries.
    levelsByName[upgrade.name] = cache[upgrade.name].costs.map((cost) => Math.round(cost))
  }

  const levelsSource = `/**
 * Per-level coin cost to advance each Workshop Enhancement category,
 * index = current level, value = coins to go from that level to the next
 * (the same convention workshopLevels.js already uses). Sourced from
 * mytower.app (/workshop/enhancement/{tree}/{name}), replacing the
 * community Google Sheet this data was previously hand-transcribed from
 * -- see Completed-Questions.md's OQ-39 and OQ-39-Data-Source-Migration.md
 * (Phase 2). \`enhancementCategories.js\` itself (names, \`quantity\`, and
 * the OQ-6 \`unlocksAt\` thresholds) is untouched -- mytower.app doesn't
 * model the tree-threshold-gating mechanic at all, and its own max level
 * already matched every category here exactly, so there was nothing to
 * migrate on that side.
 *
 * Carries mytower.app's own display precision (~3 significant figures,
 * rounded), matching what the Google Sheet's own data already carried
 * (see the Google Sheet's own condensed display values) -- no precision
 * regression from this migration, unlike the exact-decimal
 * tower-idle-toolkit data Phase 1 moved away from.
 *
 * Generated by scripts/extract-enhancement-data.mjs +
 * scripts/generate-enhancement-data-files.mjs -- do not hand-edit.
 * Re-run both after a suspected game patch.
 */
export const ENHANCEMENT_LEVELS = ${JSON.stringify(levelsByName)}
`

  writeFileSync(LEVELS_PATH, levelsSource)
  console.log(`Wrote ${LEVELS_PATH}`)
}

main()
