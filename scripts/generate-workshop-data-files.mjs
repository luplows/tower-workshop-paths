#!/usr/bin/env node
/**
 * Turns `.cache/workshop-extraction.json` (built by
 * extract-workshop-data.mjs) into the two data files this project's app
 * code actually imports:
 *
 * - `src/data/workshopUpgradeList.js` -- per-tree upgrade name/order/max
 *   level, replacing tower-idle-toolkit's ATTACK_UPGRADES/etc.
 * - `src/data/workshopLevels.js` -- per-upgrade cost arrays, replacing
 *   tower-idle-toolkit's WORKSHOP_LEVELS. Same flat `{ [name]: [cost,
 *   cost, ...] }` shape enhancementLevels.js already uses.
 *
 * A separate step from extraction itself so the (slow, network-bound)
 * scrape and the (instant, deterministic) file-generation can be re-run
 * independently -- e.g. regenerating the files after hand-editing the
 * cache to patch one bad value, without re-scraping everything.
 *
 * Usage: npm run generate:workshop-data-files
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { WORKSHOP_CATEGORIES } from '../src/data/workshopCategories.js'

const CACHE_PATH = new URL('../.cache/workshop-extraction.json', import.meta.url)
const UPGRADE_LIST_PATH = new URL('../src/data/workshopUpgradeList.js', import.meta.url)
const LEVELS_PATH = new URL('../src/data/workshopLevels.js', import.meta.url)

function loadCache() {
  if (!existsSync(CACHE_PATH)) {
    throw new Error(`No cache at ${CACHE_PATH}. Run \`npm run extract:workshop-data\` first.`)
  }
  return JSON.parse(readFileSync(CACHE_PATH, 'utf8'))
}

function main() {
  const cache = loadCache()
  const treeByName = new Map()
  for (const category of WORKSHOP_CATEGORIES) {
    for (const upgrade of category.upgrades) treeByName.set(upgrade.name, category.id)
  }

  const missingUpgrades = []
  const incompleteUpgrades = []
  for (const name of treeByName.keys()) {
    const entry = cache[name]
    if (!entry || entry.error) {
      missingUpgrades.push(name)
      continue
    }
    if (entry.missing) incompleteUpgrades.push(`${name} (${entry.missing.length} levels)`)
  }
  if (missingUpgrades.length > 0) {
    throw new Error(`Cache is missing these upgrades entirely: ${missingUpgrades.join(', ')}`)
  }
  if (incompleteUpgrades.length > 0) {
    throw new Error(`Cache has incomplete data for: ${incompleteUpgrades.join('; ')}`)
  }

  const upgradeListByTree = { attack: [], defense: [], utility: [] }
  const levelsByName = {}
  for (const category of WORKSHOP_CATEGORIES) {
    for (const upgrade of category.upgrades) {
      const entry = cache[upgrade.name]
      upgradeListByTree[category.id].push({ name: upgrade.name, quantity: entry.maxLevel })
      // Rounded: parseAbbreviated's float multiplication (e.g. 8.2 * 1e6)
      // routinely produces meaningless trailing noise like
      // 8199999.999999999 -- not real precision, since the source data
      // itself only ever carries ~3 significant figures to begin with.
      levelsByName[upgrade.name] = entry.costs.map((cost) => Math.round(cost))
    }
  }

  const upgradeListSource = `/**
 * Every Workshop upgrade, grouped and ordered by tree exactly as shown
 * in-game -- name and max level (\`quantity\`, enforced as a hard input
 * limit by UpgradeLevelInput). Sourced from mytower.app
 * (/workshop/upgrade/{tree}/{name}, the \`M\` field), replacing
 * tower-idle-toolkit's ATTACK_UPGRADES/DEFENSE_UPGRADES/UTILITY_UPGRADES
 * -- see Open-Questions.md's OQ-39 and OQ-39-Data-Source-Migration.md.
 *
 * Generated by scripts/extract-workshop-data.mjs +
 * scripts/generate-workshop-data-files.mjs -- do not hand-edit. Re-run
 * both after a suspected game patch.
 */
export const WORKSHOP_UPGRADE_LIST = ${JSON.stringify(upgradeListByTree)}
`

  const levelsSource = `/**
 * Per-level coin cost to advance each Workshop upgrade, index = current
 * level, value = coins to go from that level to the next (the same
 * convention enhancementLevels.js already uses). Sourced from
 * mytower.app (/workshop/upgrade/{tree}/{name}), replacing
 * tower-idle-toolkit's WORKSHOP_LEVELS -- see Open-Questions.md's OQ-39
 * and OQ-39-Data-Source-Migration.md.
 *
 * Carries mytower.app's own display precision (~3 significant figures,
 * rounded), not tower-idle-toolkit's exact decimals -- an accepted
 * tradeoff (see the plan doc), and no worse than what a player actually
 * sees in-game. Every level 0..quantity-1 has a real value here; unlike
 * tower-idle-toolkit, there's no gap needing a sentinel/undefined case.
 *
 * Generated by scripts/extract-workshop-data.mjs +
 * scripts/generate-workshop-data-files.mjs -- do not hand-edit. Re-run
 * both after a suspected game patch.
 */
export const WORKSHOP_LEVELS = ${JSON.stringify(levelsByName)}
`

  writeFileSync(UPGRADE_LIST_PATH, upgradeListSource)
  writeFileSync(LEVELS_PATH, levelsSource)
  console.log(`Wrote ${UPGRADE_LIST_PATH}`)
  console.log(`Wrote ${LEVELS_PATH}`)
}

main()
